"""Постобработка текста после распознавания речи (whisper)."""

import re

# Словарь типичных ошибок whisper-base.
# Ключ — регулярное выражение (учитывает словоформы), значение — замена.
FIXES = {
    # Задачи
    r'\bсадач\w*': 'задач',
    r'\bзадачь\b': 'задач',
    r'\bнада\b': 'надо',
    r'\bвыполнил\b': 'выполнил',
    r'\bсделат\b': 'сделать',
    r'\bсделал\b': 'сделал',

    # Сыроварение (твои частые слова)
    r'\bсыровор\w*': 'сыровар',
    r'\bсварится\b': 'сварить',
    r'\bсвариться\b': 'сварить',
    r'\bсыра\b': 'сыра',
    r'\bмалако\b': 'молоко',

    # Звонки и дела
    r'\bпозван\w*': 'позвони',
    r'\bкупит\b': 'купить',
    r'\bнаписать\b': 'написать',

    # Идеи
    r'\bидеи\b': 'идеи',
    r'\bидею\b': 'идею',
}


def fix_text(text: str) -> str:
    """Исправляет типичные ошибки распознавания."""
    if not text:
        return text

    fixed = text
    for pattern, replacement in FIXES.items():
        # Заменяем без учета регистра (флаг re.IGNORECASE)
        fixed = re.sub(pattern, replacement, fixed, flags=re.IGNORECASE)

    return fixed
